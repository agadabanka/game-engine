// tools/upgrade-mechanics.mjs — RETROFIT an already-made game with the mechanics pipeline.
//
// Point it at ANY previously-built game. It (1) ensures a mechanics.json (the spec — runs deconstruct
// if missing), (2) adapts the game's existing levels to solver rooms, (3) runs the VERB-AWARE solver
// on each, and (4) writes a depth AUDIT: is each level solvable, which verbs it USES vs REQUIRES, how
// tight it is, and a verdict — so you can SEE whether a level has real mechanical depth (a required
// dash/wall-jump) or is garnish (a dumb bot would clear it). Read-only by default; --write saves the
// spec + MECHANICS-AUDIT.md into the repo and stamps the `deconstruct` stage.
//
//   node tools/upgrade-mechanics.mjs <gameDir> [--genre <g>] [--write]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { genreFor, validate } from './lib/mechspec.mjs';
import { solveRoom } from './lib/solver.mjs';
import { loadLevels, toRoom } from './lib/leveladapt.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/upgrade-mechanics.mjs <gameDir> [--genre <g>] [--write]'); process.exit(2); }
const WRITE = process.argv.includes('--write');
const genreArg = process.argv.includes('--genre') ? process.argv[process.argv.indexOf('--genre') + 1] : null;

const meta = JSON.parse(fs.readFileSync(path.join(dir, 'GAME_META.json'), 'utf8'));
const game = meta.name || path.basename(dir);

// 1) ensure the mechanics SPEC (the contract). deconstruct writes it; we read it back.
const specPath = path.join(dir, 'mechanics.json');
if (!fs.existsSync(specPath) || WRITE) {
  const args = [path.join(HERE, 'deconstruct.mjs'), dir]; if (genreArg) args.push('--genre', genreArg);
  try { execFileSync('node', args, { stdio: 'ignore' }); } catch (e) {}
}
const spec = fs.existsSync(specPath) ? JSON.parse(fs.readFileSync(specPath, 'utf8')) : null;
const genre = (spec && spec.genre) || genreArg || genreFor(`${meta.name} ${meta.tagline} ${meta.verb} ${meta.genre}`);

console.log(`\n🔧 upgrade-mechanics · ${game}\n   genre: ${genre}${spec ? '' : '  (no spec)'}`);

// 2-3) adapt + solver-audit each level
const { levels, error } = loadLevels(dir);
if (error) console.log(`   levels: ${error}`);
const rows = [];
levels.forEach((L, i) => {
  const room = toRoom(L);
  if (room.format === 'n/a') { rows.push({ n: i + 1, name: L.name || `L${i + 1}`, format: 'n/a' }); return; }
  let r = { solvable: false };
  if (spec) try { r = solveRoom(room, spec); } catch (e) { r = { solvable: false, reason: e.message }; }
  const required = (r.requires || []);
  const verdict = !r.solvable ? 'unsolvable-by-solver' : required.length ? `depth: requires ${required.join('+')}` : 'depth: THIN (no required tech — a dumb bot clears it)';
  rows.push({ n: i + 1, name: L.name || room.name || `L${i + 1}`, format: room.format, solvable: r.solvable, used: r.usedVerbs || [], requires: required, tightness: r.tightness, difficulty: r.difficulty, verdict, reason: r.reason });
});

// 4) print + (optionally) write the audit
const applicable = rows.filter((x) => x.format !== 'n/a');
console.log(`   levels adapted: ${applicable.length}/${rows.length}\n`);
for (const x of rows) {
  if (x.format === 'n/a') { console.log(`   ·  ${x.n}. ${x.name}: format n/a (genre not a platformer — solver retrofit skipped)`); continue; }
  console.log(`   ${x.solvable ? '✓' : '✗'}  ${x.n}. ${x.name}  [${x.format}]  used=[${x.used.join(',')}] requires=[${x.requires.join(',')}] tight=${x.tightness ?? '-'} diff=${x.difficulty ?? '-'}  → ${x.verdict}${x.reason ? ' (' + x.reason + ')' : ''}`);
}
const thin = applicable.filter((x) => x.solvable && x.requires.length === 0).length;
const deep = applicable.filter((x) => x.requires.length).length;
console.log(`\n   summary: ${deep} level(s) with required depth, ${thin} thin/garnish, ${applicable.filter((x) => !x.solvable).length} unsolvable-by-solver.`);
if (applicable.length && thin > deep) console.log(`   → this game is mostly garnish-depth; add rooms that REQUIRE the dash/wall-jump (build-in-steps + solveRoom) to deepen it.`);

if (WRITE && spec) {
  const md = `# Mechanics audit — ${game}\n\nGenerated by \`tools/upgrade-mechanics.mjs\`. Genre: **${genre}**. ` +
    `Each level adapted to a solver room and checked with the verb-aware solver: which verbs it USES, which it REQUIRES (load-bearing — remove it and the level is unsolvable), tightness (px to nearest spike) and difficulty.\n\n` +
    `| # | level | format | solvable | used | **requires** | tight | diff | verdict |\n|---|---|---|---|---|---|---|---|---|\n` +
    rows.map((x) => x.format === 'n/a' ? `| ${x.n} | ${x.name} | n/a | — | — | — | — | — | genre not a platformer |`
      : `| ${x.n} | ${x.name} | ${x.format} | ${x.solvable ? '✓' : '✗'} | ${x.used.join(' ')} | ${x.requires.join(' ') || '—'} | ${x.tightness ?? '-'} | ${x.difficulty ?? '-'} | ${x.verdict} |`).join('\n') +
    `\n\n**Summary:** ${deep} level(s) demand real tech, ${thin} are garnish-depth.` +
    (thin > deep ? ` To deepen: author **rooms that REQUIRE the dash/wall-jump** (build-in-steps via \`tools/lib/rooms.mjs\` + \`solveRoom\`), and re-run this audit.` : ` Healthy depth.`) + `\n`;
  fs.writeFileSync(path.join(dir, 'MECHANICS-AUDIT.md'), md);
  const v = validate(spec);
  meta.stages = meta.stages || {}; meta.stages.deconstruct = 'done';
  fs.writeFileSync(path.join(dir, 'GAME_META.json'), JSON.stringify(meta, null, 2) + '\n');
  console.log(`\n   ✅ wrote mechanics.json (${v.ok ? 'valid' : 'INVALID'}) + MECHANICS-AUDIT.md; stamped deconstruct stage.`);
} else if (spec) {
  console.log(`\n   (read-only) re-run with --write to save mechanics.json + MECHANICS-AUDIT.md into the repo.`);
}
